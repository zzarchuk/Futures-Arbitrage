спреды = [1, 2, 3, 4, 5, 5.1, 5.2, 6, 7, 8, 29, 30, 31, 32, 33, 34, 35, 36]
разрыв_порог = 5  # если разница между соседними значениями больше 5 → новая свеча

# Список для всех свечей
свечи = []

# Временная переменная для текущей свечи
текущая_свеча = []

for индекс, значение in enumerate(спреды):
    
    # Если текущая свеча пустая, начинаем новую
    if not текущая_свеча:
        текущая_свеча.append(значение)
        continue
    
    # Если разница между текущим значением и последним в свечи больше порога → новая свеча
    if значение - текущая_свеча[-1] > разрыв_порог:
        свечи.append(текущая_свеча)  # сохраняем старую свечу
        текущая_свеча = [значение]    # начинаем новую свечу
    else:
        # иначе продолжаем добавлять в текущую свечу
        текущая_свеча.append(значение)

# После цикла нужно добавить последнюю свечу
if текущая_свеча:
    свечи.append(текущая_свеча)

print(свечи)